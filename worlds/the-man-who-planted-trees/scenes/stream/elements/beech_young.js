// One of Elzéard's beeches at the slope's far edge, planted after the maples died (2.6: «Теперь буки»): a sapling a
// hand high in the second chapter, a young beech twice a man's height in the third (lib.js: beech); none in the first
const y = e.state.year;
if (y >= 20) e.lib.beech(g, e, { h: 5.2, w: 1.7, wind: 0.18 });
else if (y >= 6) e.lib.beech(g, e, { h: 0.4, w: 0.15, wind: 0 });
